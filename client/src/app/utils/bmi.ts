const BMI_FOR_AGE_MIN_MONTHS = BMI_FOR_AGE_BOYS[0][0];
const BMI_FOR_AGE_MAX_MONTHS = BMI_FOR_AGE_BOYS[BMI_FOR_AGE_BOYS.length - 1][0];

export type NutritionalStatus = 'Severely Wasted' | 'Wasted' | 'Normal' | 'Overweight' | 'Obese';

/**
 * Classifies BMI-for-age per the DOH/DepEd reference table. Returns null
 * (never a guess) when the BMI, age, or sex is missing, or the child's age
 * falls outside the table's 6–19 year coverage — there is no reference for
 * a younger child, so no category is claimed rather than one being invented.
 */
export function classifyNutritionalStatus(
  bmi: number | null | undefined,
  ageMonths: number | null | undefined,
  sex: string | null | undefined,
): NutritionalStatus | null {
  if (bmi == null || ageMonths == null || !sex) return null;
  if (ageMonths < BMI_FOR_AGE_MIN_MONTHS || ageMonths > BMI_FOR_AGE_MAX_MONTHS) return null;
  const table = sex === 'Male' ? BMI_FOR_AGE_BOYS : sex === 'Female' ? BMI_FOR_AGE_GIRLS : null;
  if (!table) return null;
  const clampedMonths = Math.round(ageMonths);
  const row = table.find((r) => r[0] === clampedMonths) ?? table[table.length - 1];
  const [, severelyWastedMax, wastedMax, normalMax, overweightMax] = row;
  if (bmi <= severelyWastedMax) return 'Severely Wasted';
  if (bmi <= wastedMax) return 'Wasted';
  if (bmi <= normalMax) return 'Normal';
  if (bmi <= overweightMax) return 'Overweight';
  return 'Obese';
}
